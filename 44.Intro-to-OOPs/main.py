# intro to oops in python
# we learn about oops in python
# oops stands for object oriented programming system
# oops is a programming paradigm that uses "objects" to design software
# an object is an instance of a class
# a class is a blueprint for creating objects
# oops allows us to model real-world entities as objects in our code
# oops has four main principles: encapsulation, inheritance, polymorphism, and abstraction
# 1. Encapsulation: Bundling data and methods that operate on that data within a single unit (class)
# 2. Inheritance: Mechanism by which one class can inherit properties and methods from another class
# 3. Polymorphism: Ability to present the same interface for different data types
# 4. Abstraction: Hiding complex implementation details and showing only the necessary features of an object
